import React, { useState } from 'react';
import { SentenceAnalysis } from '../types';
import { AlertTriangle, Eye, EyeOff } from 'lucide-react';

interface SentenceHighlighterProps {
  sentences?: SentenceAnalysis[];
  originalText?: string;
}

export const SentenceHighlighter: React.FC<SentenceHighlighterProps> = ({
  sentences,
}) => {
  const [activeSentence, setActiveSentence] = useState<SentenceAnalysis | null>(null);
  const [showHighlights, setShowHighlights] = useState<boolean>(true);

  if (!sentences || sentences.length === 0) {
    return null;
  }

  return (
    <div className="rounded-2xl bg-navy-900/60 backdrop-blur-xl border border-slate-800 p-6 shadow-xl">
      <div className="flex flex-wrap items-center justify-between gap-3 mb-4 pb-3 border-b border-slate-800">
        <div>
          <h4 className="text-base font-bold text-white flex items-center gap-2">
            Sentence-Level Pattern Analysis
            <span className="text-xs font-normal px-2 py-0.5 rounded-full bg-electric-500/10 border border-electric-500/30 text-electric-400">
              Experimental
            </span>
          </h4>
          <p className="text-xs text-slate-400 mt-0.5">
            Individual sentences evaluated independently. Hover to inspect segment signals.
          </p>
        </div>

        <button
          onClick={() => setShowHighlights(!showHighlights)}
          className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium bg-slate-800 text-slate-300 hover:text-white border border-slate-700 transition-colors"
        >
          {showHighlights ? (
            <>
              <EyeOff className="w-3.5 h-3.5 text-slate-400" /> Hide Highlights
            </>
          ) : (
            <>
              <Eye className="w-3.5 h-3.5 text-electric-400" /> Show Highlights
            </>
          )}
        </button>
      </div>

      {/* Mandatory Uncertainty Alert */}
      <div className="rounded-xl bg-amber-500/10 border border-amber-500/20 p-3 mb-4 text-xs text-amber-300/90 flex items-start gap-2.5">
        <AlertTriangle className="w-4 h-4 text-amber-400 shrink-0 mt-0.5" />
        <div>
          <strong className="font-semibold text-amber-200">Segment Uncertainty Notice: </strong>
          Isolated sentences lack macro-context. A highlighted sentence means only that its local phrasing, uniformity, or token frequency matches patterns often observed in LLMs. It does <span className="underline font-medium">not</span> prove that the sentence was generated by AI.
        </div>
      </div>

      {/* Rendered Text with Sentence Highlights */}
      <div className="p-5 rounded-xl bg-navy-950/80 border border-slate-800/80 text-sm leading-relaxed max-h-96 overflow-y-auto space-y-1">
        {sentences.map((item, idx) => {
          const aiPercent = Math.round(item.ai_score * 100);
          const isAiDominant = item.prediction === 'AI-Generated' && item.ai_score >= 0.55;
          const isInconclusive = item.prediction === 'Inconclusive' || (item.ai_score >= 0.45 && item.ai_score <= 0.55);

          let highlightClass = '';
          if (showHighlights) {
            if (isAiDominant) {
              highlightClass = 'bg-brandPurple-500/20 text-purple-200 border-b border-brandPurple-400/50 hover:bg-brandPurple-500/35 cursor-pointer';
            } else if (isInconclusive) {
              highlightClass = 'bg-amber-500/15 text-amber-200 border-b border-amber-400/40 hover:bg-amber-500/25 cursor-pointer';
            } else {
              highlightClass = 'hover:bg-slate-800/50 cursor-pointer';
            }
          }

          return (
            <span
              key={idx}
              onClick={() => setActiveSentence(item)}
              onMouseEnter={() => setActiveSentence(item)}
              className={`inline rounded px-1 py-0.5 transition-colors duration-150 ${highlightClass}`}
              title={`AI Score: ${aiPercent}%`}
            >
              {item.text}{' '}
            </span>
          );
        })}
      </div>

      {/* Sentence Detail Inspector Tooltip */}
      {activeSentence && (
        <div className="mt-4 p-4 rounded-xl bg-navy-950 border border-slate-800 text-xs">
          <div className="flex items-center justify-between mb-2">
            <span className="font-semibold text-slate-300">
              Selected Segment #{activeSentence.sentence_index + 1}
            </span>
            <div className="flex items-center gap-3">
              <span className="text-brandPurple-400 font-mono">
                AI Pattern: {Math.round(activeSentence.ai_score * 100)}%
              </span>
              <span className="text-emerald-400 font-mono">
                Human Pattern: {Math.round(activeSentence.human_score * 100)}%
              </span>
            </div>
          </div>
          <p className="italic text-slate-300 bg-slate-900/80 p-2.5 rounded border border-slate-800">
            "{activeSentence.text}"
          </p>
        </div>
      )}
    </div>
  );
};
